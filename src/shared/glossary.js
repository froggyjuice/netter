const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const BY_WORD = new Map(GLOSSARY.flatMap((g, i) => [g.term, ...(g.aliases ?? [])].map((w) => [w, i])));
const WORD_RE = new RegExp([...BY_WORD.keys()].sort((a, b) => b.length - a.length).map(escape).join('|'), 'g');

/** 낱말 → 풀이 (없으면 null) */
export const glossaryOf = (word) => (BY_WORD.has(word) ? GLOSSARY[BY_WORD.get(word)] : null);

/**
 * HTML 문자열 속 글자 부분의 풀이 낱말을 <span class="term" data-term="번호"> 로 감싼다 (태그 안은 건드리지 않음).
 * 한 줄에서 같은 낱말은 처음 한 번만.
 */
export function wrapTerms(html) {
  const seen = new Set();
  return String(html)
    .split(/(<[^>]*>)/)
    .map((part) =>
      part.startsWith('<')
        ? part
        : part.replace(WORD_RE, (w) => {
            const i = BY_WORD.get(w);
            if (seen.has(i)) return w;
            seen.add(i);
            return `<span class="term" role="button" tabindex="0" data-term="${i}">${w}</span>`;
          }),
    )
    .join('');
}
